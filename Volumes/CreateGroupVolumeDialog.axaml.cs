using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Arkadia.Data;
using Avalonia.Controls;
using Avalonia.Interactivity;

namespace Arkadia;

/// <summary>
/// Thin Group sibling of <see cref="CreateVolumeDialog"/>. Header-only: pick a Group, auto-suggest
/// <c>{group-id}-NNN</c> (shared numbering), optionally suggest capacity by aggregating existing per-leaf
/// read-only unassigned-present stats, and produce a Group-owned <see cref="VolumeRecord"/>
/// (<c>GroupId</c> set, <c>DatLineId</c> NULL, status <c>init</c>, actual 0). No filesystem, no planning,
/// no artifact/location rows — persistence is the caller's <c>SaveVolume</c>.
/// </summary>
public partial class CreateGroupVolumeDialog : Window
{
    private readonly List<DatGroupRecord>  _groups;
    private readonly IReadOnlyList<string> _existingLabels;
    private readonly CatalogService        _catalog;
    private readonly string                _dataDir;

    private bool _labelAutoGenerated = true;
    private bool _settingLabel       = false;

    public VolumeRecord? Result { get; private set; }

    // Parameterless ctor required by the Avalonia XAML compiler.
    public CreateGroupVolumeDialog() : this([], [], null!, string.Empty) { }

    public CreateGroupVolumeDialog(
        List<DatGroupRecord>  groups,
        IReadOnlyList<string> existingLabels,
        CatalogService        catalog,
        string                dataDir)
    {
        InitializeComponent();

        _groups         = [.. groups.OrderBy(g => g.DisplayName, StringComparer.OrdinalIgnoreCase)];
        _existingLabels = existingLabels;
        _catalog        = catalog;
        _dataDir        = dataDir;

        GroupCombo.ItemsSource   = _groups.Select(g => $"{g.DisplayName}  ·  {g.Id.Value}").ToList();
        GroupCombo.SelectedIndex = _groups.Count > 0 ? 0 : -1;

        UpdateSuggestedLabel();
        Validate();
    }

    private DatGroupRecord? CurrentGroup()
    {
        var idx = GroupCombo.SelectedIndex;
        return idx >= 0 && idx < _groups.Count ? _groups[idx] : null;
    }

    private void OnGroupChanged(object? sender, SelectionChangedEventArgs e)
    {
        if (_labelAutoGenerated) UpdateSuggestedLabel();
        Validate();
    }

    private void OnLabelChanged(object? sender, TextChangedEventArgs e)
    {
        if (!_settingLabel) _labelAutoGenerated = false;
        Validate();
    }

    private void UpdateSuggestedLabel()
    {
        if (CurrentGroup() is not { } group) return;
        _settingLabel   = true;
        LabelInput.Text = Volumes.VolumeLabelNumbering.SuggestLabel(_existingLabels, group.Id.Value);
        _settingLabel   = false;
    }

    // Capacity suggestion: aggregate the existing per-leaf read-only unassigned-present stats (no planning).
    private void OnSuggestSize(object? sender, RoutedEventArgs e)
    {
        if (CurrentGroup() is not { } group) return;

        long totalUnassigned = 0;
        foreach (var leaf in _catalog.GetLeavesForGroup(group.Id.Value))
        {
            if (leaf.DatLine.DataStorePath.Length == 0) continue;
            var dbPath = Path.Combine(_dataDir, leaf.DatLine.DataStorePath);
            if (!File.Exists(dbPath)) continue;

            var assignedIds     = _catalog.GetAssignedDerivedIdsByDatLine(leaf.DatLine.Id);
            var (_, unassigned) = new DatLineStore(dbPath).GetUnassignedPresentStats(assignedIds);
            totalUnassigned += unassigned;
        }

        var suggestedGb = (long)(totalUnassigned * 1.10) / (1024.0 * 1024 * 1024);
        PlannedSizeInput.Text = suggestedGb.ToString("F2", System.Globalization.CultureInfo.InvariantCulture);
    }

    private void Validate()
    {
        var label    = LabelInput.Text?.Trim()       ?? "";
        var sizeText = PlannedSizeInput.Text?.Trim() ?? "";
        bool sizeOk  = double.TryParse(sizeText, System.Globalization.NumberStyles.Any,
                           System.Globalization.CultureInfo.InvariantCulture, out var size) && size > 0;
        bool groupOk = GroupCombo.SelectedIndex >= 0;

        string? err = sizeText.Length > 0 && !sizeOk ? "Planned size must be a positive number." : null;

        ErrorText.Text          = err ?? "";
        ErrorText.IsVisible     = err is not null;
        ConfirmButton.IsEnabled = label.Length > 0 && sizeOk && groupOk && err is null;
    }

    private void OnFieldChanged(object? sender, TextChangedEventArgs e) => Validate();

    private void OnConfirm(object? sender, RoutedEventArgs e)
    {
        if (CurrentGroup() is not { } group) return;
        var sizeGb = double.Parse(PlannedSizeInput.Text!.Trim(),
                         System.Globalization.CultureInfo.InvariantCulture);

        // Group-owned header: GroupId set, DatLineId NULL, init, actual 0. No filesystem/artifacts.
        Result = new VolumeRecord
        {
            Id               = Guid.NewGuid().ToString("N"),
            Label            = LabelInput.Text!.Trim(),
            PlatformId       = group.HardwareFamilyId,
            DatLineId        = null,
            GroupId          = group.Id.Value,
            Status           = "init",
            PlannedSizeBytes = (long)(sizeGb * 1024 * 1024 * 1024),
            ActualSizeBytes  = 0,
            CreatedAt        = DateTime.UtcNow,
        };
        Close(true);
    }

    private void OnCancel(object? sender, RoutedEventArgs e) => Close(false);
}
